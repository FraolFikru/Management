def money(x) -> Decimal:
    return Decimal(str(x)).quantize(Decimal("0.01"), ROUND_HALF_UP)


def bdate(iso: str) -> str:
    """Business date in Addis Ababa for a UTC ISO timestamp."""
    return datetime.fromisoformat(iso.replace("Z", "+00:00")).astimezone(ADDIS).date().isoformat()


def lit(v) -> str:
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, Decimal)):
        return str(v)
    if isinstance(v, float):
        return repr(round(v, 6))
    if isinstance(v, (dict, list)):
        v = json.dumps(v, ensure_ascii=False, separators=(",", ":"))
    return "'" + str(v).replace("'", "''") + "'"


def phc_scrypt(secret: str, salt: str) -> str:
    """Demo hash in PHC-like form; the API verifies with hashlib.scrypt."""
    s = hashlib.sha256(salt.encode()).digest()[:16]
    h = hashlib.scrypt(secret.encode(), salt=s, n=2**14, r=8, p=1, dklen=32)
    return f"$scrypt$ln=14,r=8,p=1${s.hex()}${h.hex()}"


def initials(name: str) -> str:
    return "".join(p[0] for p in name.split()[:2]).upper()


class Sql:
    """Collects INSERTs per table, in dependency order."""

    def __init__(self) -> None:
        self.parts: list[tuple[str, list[dict]]] = []

    def add(self, table: str, rows: list[dict]) -> None:
        if rows:
            self.parts.append((table, rows))

    def render(self, header: str) -> str:
        out = [header]
        for table, rows in self.parts:
            out.append(f"\n-- {table}: {len(rows)} rows")
            groups: dict[tuple, list] = {}
            for r in rows:  # one INSERT per column set, so omitted columns get their DEFAULT
                groups.setdefault(tuple(r), []).append(r)
            for cols, grows in groups.items():
                for i in range(0, len(grows), 200):
                    chunk = grows[i:i + 200]
                    vals = ",\n  ".join("(" + ", ".join(lit(r.get(c)) for c in cols) + ")" for r in chunk)
                    out.append(f"INSERT INTO {table} ({', '.join(cols)}) VALUES\n  {vals};")
        return "\n".join(out) + "\n"


class Report:
    def __init__(self) -> None:
        self.lines: dict[str, list[str]] = defaultdict(list)

    def add(self, section: str, line: str) -> None:
        self.lines[section].append(line)

    def render(self) -> str:
        out = ["# Eirsha Ops — seed import report", "",
               "Generated by `seed/build_seed.py`. Review the conflicts before going live.", ""]
        for sec, lines in self.lines.items():
            out += [f"## {sec}", ""] + [f"- {l}" for l in lines] + [""]
        return "\n".join(out)


