let lang: Lang = "en";
export const LANGS: { code: Lang; label: string }[] = [{ code: "en", label: "EN" }, { code: "am", label: "አማ" }, { code: "om", label: "OM" }];
export const getLang = (): Lang => lang;
export function setLang(l: Lang): void { lang = l; document.documentElement.lang = l; }

export function t(key: string, vars: Record<string, string | number> = {}): string {
  const row = dict[key];
  let s = lang === "en" || !row ? key : row[lang === "am" ? 0 : 1] || key;
  for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
export const nm = (n: Names): string => n[lang] || n.en;

export function money(n: number): string {
  const v = Math.round(n * 100) / 100;
  return `ETB ${v.toLocaleString("en-US", { minimumFractionDigits: Number.isInteger(v) ? 0 : 2, maximumFractionDigits: 2 })}`;
}

/** "8m", "1h 05" — how long a table has been open. */
export function since(iso: string, now = Date.now()): string {
  const m = Math.max(0, Math.floor((now - new Date(iso).getTime()) / 60000));
  return m < 60 ? `${m} ${t("min")}` : `${Math.floor(m / 60)}h ${String(m % 60).padStart(2, "0")}`;
}
