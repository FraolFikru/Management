export function translate(key: string, lang: Lang, vars?: Record<string, string | number>): string {
  let s = lang === "en" ? key : (dict[key]?.[lang] ?? key);
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

